"""LaTeX versions of the main result tables, for ``\\input`` into a report.

Each table is a booktabs ``table`` float (needs ``\\usepackage{booktabs}``, plus
``graphicx`` for the wide ones, which are scaled to ``\\linewidth``).  Means are
shown with their 95% CI as ``mean [low, high]``, win rates as percentages, and
names as they appear in the game.
"""

from __future__ import annotations

import math
import re

import pandas as pd

from balatro_analysis import metrics, stats
from balatro_analysis.loader import Run
from balatro_analysis.names import Names

_PRETTY = Names(pretty=True)
WIDE = 6  # tables with more columns than this are scaled to the text width

_ESCAPES = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def escape(text: object) -> str:
    """Escape LaTeX special characters in plain text."""
    return re.sub(r"[\\&%$#_{}~^]", lambda m: _ESCAPES[m.group()], str(text))


def _nan(x: object) -> bool:
    return x is None or (isinstance(x, float) and math.isnan(x))


def num(x: object, digits: int = 2) -> str:
    return "--" if _nan(x) else f"{x:.{digits}f}"


def pct(x: object) -> str:
    return "--" if _nan(x) else f"{100 * x:.1f}\\%"


def pval(p: object) -> str:
    if _nan(p):
        return "--"
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def with_ci(mean: object, low: object, high: object, fmt=num) -> str:
    """``mean [low, high]``; just the mean when there is no interval."""
    if _nan(low) or _nan(high):
        return fmt(mean)
    return f"{fmt(mean)} [{fmt(low)}, {fmt(high)}]"


def table(rows: list[list[str]], headers: list[str], caption: str, label: str, align: str) -> str:
    """A booktabs table float.  Cells and headers must already be LaTeX."""
    body = "\n".join(" & ".join(r) + r" \\" for r in rows)
    tabular = (
        f"\\begin{{tabular}}{{{align}}}\n\\toprule\n"
        + " & ".join(headers)
        + " \\\\\n\\midrule\n"
        + body
        + "\n\\bottomrule\n\\end{tabular}"
    )
    if len(headers) > WIDE:
        tabular = f"\\resizebox{{\\linewidth}}{{!}}{{%\n{tabular}}}"
    return (
        "% Generated by balatro-run-analysis; needs \\usepackage{booktabs}"
        + (" and graphicx" if len(headers) > WIDE else "")
        + f"\n\\begin{{table}}[htbp]\n\\centering\n\\caption{{{caption}}}\n"
        + f"\\label{{tab:{label}}}\n{tabular}\n\\end{{table}}\n"
    )


def _outcome_cells(ci: pd.DataFrame, key: str) -> dict[str, list[str]]:
    """Per ``key`` (run or group): the ante / win rate / return cells with CIs."""
    out: dict[str, list[str]] = {}
    for name, g in ci.groupby(key, sort=False):
        by = g.set_index("outcome")
        cells = []
        for outcome, fmt in (("ante reached", num), ("win rate", pct), ("return", num)):
            if outcome in by.index:
                r = by.loc[outcome]
                cells.append(with_ci(r["mean"], r["ci_low"], r["ci_high"], fmt))
            else:
                cells.append("--")
        out[name] = cells
    return out


OUTCOME_HEADERS = ["Ante reached", "Win rate", "Return"]


def summary(runs: list[Run]) -> str:
    s = metrics.summary(runs)
    rows = [
        [
            escape(r["run"]),
            escape(r["shop agent"]),
            escape(r["play agent"]),
            escape(_PRETTY.items(r["decks"])),
            escape(_PRETTY.stakes(r["stakes"])),
            str(r["episodes"]),
            num(r["mean ante"]),
            str(r["max ante"]) if not _nan(r["max ante"]) else "--",
            pct(r["win rate"]),
        ]
        for _, r in s.iterrows()
    ]
    headers = ["Run", "Shop agent", "Play agent", "Decks", "Stakes", "Episodes"]
    headers += ["Mean ante", "Max ante", "Win rate"]
    return table(
        rows, headers, "Runs: what was trained and how far it got.", "summary", "lllll" + "r" * 4
    )


def summary_ci(runs: list[Run]) -> str:
    ci = stats.summary_ci(runs)
    if ci.empty:
        return ""
    episodes = ci.groupby("run", sort=False)["episodes"].max()
    rows = [
        [escape(run), str(episodes[run]), *cells]
        for run, cells in _outcome_cells(ci, "run").items()
    ]
    return table(
        rows,
        ["Run", "Episodes", *OUTCOME_HEADERS],
        "Mean outcome per run with 95\\% CI (bootstrap; Wilson for win rate).",
        "summary_ci",
        "lrrrr",
    )


def run_comparison(runs: list[Run], baseline: str) -> str:
    c = stats.compare(runs, baseline)
    if c.empty:
        return ""
    rows = [
        [
            escape(r["run"]),
            str(r["episodes"]),
            with_ci(r["mean_ante_diff"], r["diff_ci_low"], r["diff_ci_high"]),
            num(r["rank_biserial"]),
            pval(r["mann_whitney_p"]),
            pct(r["win_rate_diff"]),
            pval(r["fisher_p"]),
            str(r["paired_episodes"]),
            num(r["paired_mean_diff"]),
            pval(r["wilcoxon_p"]),
        ]
        for _, r in c.iterrows()
    ]
    headers = [
        "Run",
        "Episodes",
        r"$\Delta$ mean ante [95\% CI]",
        r"$r_{rb}$",
        r"$p_{MW}$",
        r"$\Delta$ win rate",
        r"$p_{\mathrm{Fisher}}$",
        "Paired",
        r"Paired $\Delta$",
        r"$p_{W}$",
    ]
    caption = (
        f"Each run against {escape(baseline)}: difference in mean ante (bootstrap CI), "
        "Mann-Whitney $U$ with rank-biserial effect size, win rate by Fisher's exact test, "
        "and the paired difference on shared seeds (Wilcoxon signed-rank)."
    )
    return table(rows, headers, caption, "run_comparison", "lr" + "r" * 8)


def group_summary(runs: list[Run]) -> str:
    ci = stats.group_summary(runs)
    if ci.empty:
        return ""
    first = ci.groupby("group", sort=False)[["runs", "episodes"]].first()
    rows = [
        [escape(g), str(first.loc[g, "runs"]), str(first.loc[g, "episodes"]), *cells]
        for g, cells in _outcome_cells(ci, "group").items()
    ]
    return table(
        rows,
        ["Group", "Runs", "Episodes", *OUTCOME_HEADERS],
        "Mean outcome per group: mean of the runs' means, 95\\% Student-$t$ CI across "
        "runs (training seeds).",
        "group_summary",
        "lrrrrr",
    )


def group_comparison(runs: list[Run], baseline: str) -> str:
    c = stats.compare_groups(runs, baseline)
    if c.empty:
        return ""
    rows = [
        [
            escape(r["group"]),
            str(r["runs"]),
            with_ci(r["ante_diff"], r["ante_ci_low"], r["ante_ci_high"]),
            pval(r["ante_welch_p"]),
            with_ci(r["win_rate_diff"], r["win_rate_ci_low"], r["win_rate_ci_high"], pct),
            pval(r["win_rate_welch_p"]),
        ]
        for _, r in c.iterrows()
    ]
    headers = [
        "Group",
        "Runs",
        r"$\Delta$ mean ante [95\% CI]",
        "$p$",
        r"$\Delta$ win rate [95\% CI]",
        "$p$",
    ]
    caption = (
        f"Each group against {escape(baseline)}, one observation per run (training seed): "
        "Welch's $t$-test and its 95\\% CI."
    )
    return table(rows, headers, caption, "group_comparison", "lrrrrr")


def _iqm_table(runs: list[Run], by_group: bool) -> str:
    iq = stats.iqm_summary(runs, by_group)
    if iq.empty:
        return ""
    key = "group" if by_group else "run"
    rows = []
    for name, g in iq.groupby(key, sort=False):
        by = g.set_index("outcome")
        cells = [
            with_ci(by.loc[o, "iqm"], by.loc[o, "iqm_low"], by.loc[o, "iqm_high"])
            if o in by.index
            else "--"
            for o in ("ante reached", "return")
        ]
        first = g.iloc[0]
        rows.append(
            [escape(name), str(first["runs"]), str(first["games"]), *cells, escape(first["method"])]
        )
    how = (
        "for groups whose runs played the same eval games, training seeds redrawn within each "
        "game (rliable's stratified bootstrap); otherwise episodes redrawn within each run"
        if by_group
        else "episodes redrawn within the run"
    )
    return table(
        rows,
        [key.capitalize(), "Runs", "Games", "Ante reached IQM", "Return IQM", "Bootstrap"],
        "Interquartile mean (IQM; Agarwal et al., 2021) with 95\\% stratified bootstrap CI: "
        f"{how}.",
        f"{'group_' if by_group else ''}iqm",
        "lrrrrl",
    )


def _improvement_table(runs: list[Run], baseline: str, by_group: bool) -> str:
    poi = stats.improvement(runs, baseline, by_group)
    if poi.empty:
        return ""
    key = "group" if by_group else "run"
    rows = [
        [
            escape(r[key]),
            str(r["games"]),
            with_ci(r["p_improvement"], r["p_low"], r["p_high"], lambda x: num(x, 3)),
            escape(r["method"]),
        ]
        for _, r in poi.iterrows()
    ]
    return table(
        rows,
        [key.capitalize(), "Games", r"$P(X > Y)$ [95\% CI]", "Pairing"],
        f"Probability of improvement over {escape(baseline)} on ante reached (Agarwal et al., "
        "2021): the chance a game of the row's agent reaches a higher ante than one of the "
        "baseline's, ties counting half; 0.5 means no difference.",
        f"{'group_' if by_group else ''}improvement",
        "lrrl",
    )


def _count(x: object) -> str:
    return "--" if _nan(x) else f"{int(x):,}".replace(",", "{,}")


def power(runs: list[Run], baseline: str, target: float) -> str:
    pw = stats.power_runs(runs, baseline, target)
    if pw.empty:
        return ""
    rows = [
        [
            escape(r["run"]),
            "yes" if r["paired"] else "no",
            str(r["games"]),
            num(r["mde"]),
            _count(r["games_needed"]),
        ]
        for _, r in pw.iterrows()
    ]
    return table(
        rows,
        ["Run", "Paired", "Games", "Detectable", f"Games for {num(target)}"],
        f"Power against {escape(baseline)} on mean ante (two-sided, $\\alpha = 0.05$, 80\\% "
        "power): the smallest difference detected with the current games, and the games per "
        f"run needed to detect a difference of {num(target)} ante.",
        "power",
        "llrrr",
    )


def group_power(runs: list[Run], target: float) -> str:
    pw = stats.power_groups(runs, target)
    if pw.empty:
        return ""
    rows = [
        [
            escape(r["group"]),
            str(r["seeds"]),
            str(r["games_per_seed"]),
            num(r["sd_game"]),
            num(r["sd_seed"]),
            num(r["mde"]),
            _count(r["seeds_needed"]),
            _count(r["seeds_needed_any_games"]),
        ]
        for _, r in pw.iterrows()
    ]
    return table(
        rows,
        [
            "Group",
            "Seeds",
            "Games/seed",
            r"SD$_{\mathrm{game}}$",
            r"SD$_{\mathrm{seed}}$",
            "Detectable",
            f"Seeds for {num(target)}",
            r"Seeds, $\infty$ games",
        ],
        "Power of a comparison between two groups like each one, on the mean of their runs' "
        "mean ante (two-sided, $\\alpha = 0.05$, 80\\% power): ante's game-to-game and "
        "seed-to-seed SDs, the smallest difference detected now, and the seeds per group needed "
        f"to detect {num(target)} ante with these games per seed and with unlimited games "
        "(-- when seed-to-seed variation is estimated as 0).",
        "group_power",
        "lrrrrrrr",
    )


def tables(runs: list[Run], target: float = 0.25) -> dict[str, str]:
    """Every LaTeX table for ``runs`` (baseline: the first run / group), keyed by
    file stem.  Group tables only when some group has more than one run."""
    if not runs:
        return {}
    out = {
        "summary": summary(runs),
        "summary_ci": summary_ci(runs),
        "run_comparison": run_comparison(runs, runs[0].name),
        "iqm": _iqm_table(runs, by_group=False),
        "improvement": _improvement_table(runs, runs[0].name, by_group=False),
        "power": power(runs, runs[0].name, target),
    }
    if any(len(g) > 1 for g in stats.groups(runs).values()):
        out["group_summary"] = group_summary(runs)
        out["group_comparison"] = group_comparison(runs, stats.group_of(runs[0]))
        out["group_iqm"] = _iqm_table(runs, by_group=True)
        out["group_improvement"] = _improvement_table(runs, stats.group_of(runs[0]), by_group=True)
        out["group_power"] = group_power(runs, target)
    return {k: v for k, v in out.items() if v}


def study_groups(groups: pd.DataFrame, caption: str, label: str) -> str:
    """A study's ``studies.group_table`` as LaTeX."""
    rows = [
        [
            escape(r.group),
            str(r.seeds),
            f"{num(r.win_pct, 1)} $\\pm$ {num(r.win_pct_sd, 1)}",
            num(r.final_round),
            num(r.ante),
            with_ci(r.ante_iqm, r.ante_iqm_low, r.ante_iqm_high),
        ]
        for r in groups.itertuples()
    ]
    headers = ["Group", "Seeds", "Win \\%", "Final round", "Ante", "IQM ante [95\\% CI]"]
    return table(rows, headers, caption, label, "lrrrrr")


def study_pairs(pairs: pd.DataFrame, caption: str, label: str) -> str:
    """A study's ``studies.pair_table`` as LaTeX: A - B paired by seed."""
    rows = [
        [
            f"{escape(r.a)} $-$ {escape(r.b)}",
            with_ci(r.ante_diff, r.ante_low, r.ante_high, lambda x: f"{x:+.3f}"),
            pval(r.p),
            r.a_better,
            with_ci(r.win_diff, r.win_low, r.win_high, lambda x: f"{x:+.1f}"),
            with_ci(r.p_improvement, r.p_low, r.p_high, lambda x: f"{x:.3f}"),
        ]
        for r in pairs.itertuples()
    ]
    headers = [
        "A $-$ B",
        "Ante [95\\% CI]",
        "$p$",
        "Seeds A ahead",
        "Win pts [95\\% CI]",
        "P(A $>$ B) [95\\% CI]",
    ]
    return table(rows, headers, caption, label, "lrrrrr")
