"""LaTeX versions of the main result tables, for ``\\input`` into a report.

Each table is a booktabs ``table`` float (needs ``\\usepackage{booktabs}``, plus
``graphicx`` for the wide ones, which are scaled to ``\\linewidth``).  Means are
shown with their 95% CI as ``mean [low, high]``, win rates as percentages, and
names as they appear in the game.
"""

from __future__ import annotations

import math
import re

import pandas as pd

from balatro_analysis import metrics, stats
from balatro_analysis.loader import Run
from balatro_analysis.names import Names

_PRETTY = Names(pretty=True)
WIDE = 6  # tables with more columns than this are scaled to the text width

_ESCAPES = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def escape(text: object) -> str:
    """Escape LaTeX special characters in plain text."""
    return re.sub(r"[\\&%$#_{}~^]", lambda m: _ESCAPES[m.group()], str(text))


def _nan(x: object) -> bool:
    return x is None or (isinstance(x, float) and math.isnan(x))


def num(x: object, digits: int = 2) -> str:
    return "--" if _nan(x) else f"{x:.{digits}f}"


def pct(x: object) -> str:
    return "--" if _nan(x) else f"{100 * x:.1f}\\%"


def pval(p: object) -> str:
    if _nan(p):
        return "--"
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def with_ci(mean: object, low: object, high: object, fmt=num) -> str:
    """``mean [low, high]``; just the mean when there is no interval."""
    if _nan(low) or _nan(high):
        return fmt(mean)
    return f"{fmt(mean)} [{fmt(low)}, {fmt(high)}]"


def table(rows: list[list[str]], headers: list[str], caption: str, label: str, align: str) -> str:
    """A booktabs table float.  Cells and headers must already be LaTeX."""
    body = "\n".join(" & ".join(r) + r" \\" for r in rows)
    tabular = (
        f"\\begin{{tabular}}{{{align}}}\n\\toprule\n"
        + " & ".join(headers)
        + " \\\\\n\\midrule\n"
        + body
        + "\n\\bottomrule\n\\end{tabular}"
    )
    if len(headers) > WIDE:
        tabular = f"\\resizebox{{\\linewidth}}{{!}}{{%\n{tabular}}}"
    return (
        "% Generated by balatro-run-analysis; needs \\usepackage{booktabs}"
        + (" and graphicx" if len(headers) > WIDE else "")
        + f"\n\\begin{{table}}[htbp]\n\\centering\n\\caption{{{caption}}}\n"
        + f"\\label{{tab:{label}}}\n{tabular}\n\\end{{table}}\n"
    )


def _outcome_cells(ci: pd.DataFrame, key: str) -> dict[str, list[str]]:
    """Per ``key`` (run or group): the ante / win rate / return cells with CIs."""
    out: dict[str, list[str]] = {}
    for name, g in ci.groupby(key, sort=False):
        by = g.set_index("outcome")
        cells = []
        for outcome, fmt in (("ante reached", num), ("win rate", pct), ("return", num)):
            if outcome in by.index:
                r = by.loc[outcome]
                cells.append(with_ci(r["mean"], r["ci_low"], r["ci_high"], fmt))
            else:
                cells.append("--")
        out[name] = cells
    return out


OUTCOME_HEADERS = ["Ante reached", "Win rate", "Return"]


def summary(runs: list[Run]) -> str:
    s = metrics.summary(runs)
    rows = [
        [
            escape(r["run"]),
            escape(r["shop agent"]),
            escape(r["play agent"]),
            escape(_PRETTY.items(r["decks"])),
            escape(_PRETTY.stakes(r["stakes"])),
            str(r["episodes"]),
            num(r["mean ante"]),
            str(r["max ante"]) if not _nan(r["max ante"]) else "--",
            pct(r["win rate"]),
        ]
        for _, r in s.iterrows()
    ]
    headers = ["Run", "Shop agent", "Play agent", "Decks", "Stakes", "Episodes"]
    headers += ["Mean ante", "Max ante", "Win rate"]
    return table(
        rows, headers, "Runs: what was trained and how far it got.", "summary", "lllll" + "r" * 4
    )


def summary_ci(runs: list[Run]) -> str:
    ci = stats.summary_ci(runs)
    if ci.empty:
        return ""
    episodes = ci.groupby("run", sort=False)["episodes"].max()
    rows = [
        [escape(run), str(episodes[run]), *cells]
        for run, cells in _outcome_cells(ci, "run").items()
    ]
    return table(
        rows,
        ["Run", "Episodes", *OUTCOME_HEADERS],
        "Mean outcome per run with 95\\% CI (bootstrap; Wilson for win rate).",
        "summary_ci",
        "lrrrr",
    )


def run_comparison(runs: list[Run], baseline: str) -> str:
    c = stats.compare(runs, baseline)
    if c.empty:
        return ""
    rows = [
        [
            escape(r["run"]),
            str(r["episodes"]),
            with_ci(r["mean_ante_diff"], r["diff_ci_low"], r["diff_ci_high"]),
            num(r["rank_biserial"]),
            pval(r["mann_whitney_p"]),
            pct(r["win_rate_diff"]),
            pval(r["fisher_p"]),
            str(r["paired_episodes"]),
            num(r["paired_mean_diff"]),
            pval(r["wilcoxon_p"]),
        ]
        for _, r in c.iterrows()
    ]
    headers = [
        "Run",
        "Episodes",
        r"$\Delta$ mean ante [95\% CI]",
        r"$r_{rb}$",
        r"$p_{MW}$",
        r"$\Delta$ win rate",
        r"$p_{\mathrm{Fisher}}$",
        "Paired",
        r"Paired $\Delta$",
        r"$p_{W}$",
    ]
    caption = (
        f"Each run against {escape(baseline)}: difference in mean ante (bootstrap CI), "
        "Mann-Whitney $U$ with rank-biserial effect size, win rate by Fisher's exact test, "
        "and the paired difference on shared seeds (Wilcoxon signed-rank)."
    )
    return table(rows, headers, caption, "run_comparison", "lr" + "r" * 8)


def group_summary(runs: list[Run]) -> str:
    ci = stats.group_summary(runs)
    if ci.empty:
        return ""
    first = ci.groupby("group", sort=False)[["runs", "episodes"]].first()
    rows = [
        [escape(g), str(first.loc[g, "runs"]), str(first.loc[g, "episodes"]), *cells]
        for g, cells in _outcome_cells(ci, "group").items()
    ]
    return table(
        rows,
        ["Group", "Runs", "Episodes", *OUTCOME_HEADERS],
        "Mean outcome per group: mean of the runs' means, 95\\% Student-$t$ CI across "
        "runs (training seeds).",
        "group_summary",
        "lrrrrr",
    )


def group_comparison(runs: list[Run], baseline: str) -> str:
    c = stats.compare_groups(runs, baseline)
    if c.empty:
        return ""
    rows = [
        [
            escape(r["group"]),
            str(r["runs"]),
            with_ci(r["ante_diff"], r["ante_ci_low"], r["ante_ci_high"]),
            pval(r["ante_welch_p"]),
            with_ci(r["win_rate_diff"], r["win_rate_ci_low"], r["win_rate_ci_high"], pct),
            pval(r["win_rate_welch_p"]),
        ]
        for _, r in c.iterrows()
    ]
    headers = [
        "Group",
        "Runs",
        r"$\Delta$ mean ante [95\% CI]",
        "$p$",
        r"$\Delta$ win rate [95\% CI]",
        "$p$",
    ]
    caption = (
        f"Each group against {escape(baseline)}, one observation per run (training seed): "
        "Welch's $t$-test and its 95\\% CI."
    )
    return table(rows, headers, caption, "group_comparison", "lrrrrr")


def tables(runs: list[Run]) -> dict[str, str]:
    """Every LaTeX table for ``runs`` (baseline: the first run / group), keyed by
    file stem.  Group tables only when some group has more than one run."""
    if not runs:
        return {}
    out = {
        "summary": summary(runs),
        "summary_ci": summary_ci(runs),
        "run_comparison": run_comparison(runs, runs[0].name),
    }
    if any(len(g) > 1 for g in stats.groups(runs).values()):
        out["group_summary"] = group_summary(runs)
        out["group_comparison"] = group_comparison(runs, stats.group_of(runs[0]))
    return {k: v for k, v in out.items() if v}
